create or replace editionable view vw_dev_object_lock_ativo as
select ad_dev_object_lock,
       object_owner,
       object_type,
       object_name,
       locked_by,
       branch_name,
       task_ref,
       lock_context,
       repo_base_ref,
       repo_head_ref,
       repo_start_sha,
       repo_end_sha,
       locked_at,
       last_heartbeat_at,
       lock_expires_at
  from dev_object_lock
 where lock_status = 'ACTIVE'
   and lock_expires_at >= systimestamp;

create or replace editionable view vw_dev_object_lock_recente as
select ad_dev_object_lock,
       object_owner,
       object_type,
       object_name,
       lock_status,
       locked_by,
       branch_name,
       task_ref,
       lock_context,
       repo_base_ref,
       repo_head_ref,
       repo_start_sha,
       repo_end_sha,
       locked_at,
       last_heartbeat_at,
       lock_expires_at,
       released_at,
       released_by,
       release_reason
  from dev_object_lock
 where nvl(released_at, last_heartbeat_at) >=
       systimestamp - interval '48' hour;

