                repo_head_ref varchar2(255 char),
                repo_start_sha varchar2(64 char),
                repo_end_sha varchar2(64 char),
                locked_at timestamp with time zone default systimestamp not null,
                last_heartbeat_at timestamp with time zone default systimestamp not null,
                lock_expires_at timestamp with time zone not null,
                released_at timestamp with time zone,
                released_by varchar2(255 char),
                release_reason varchar2(4000 byte),
                constraint dev_object_lock_pk primary key (ad_dev_object_lock),
                constraint dev_object_lock_status_ck
