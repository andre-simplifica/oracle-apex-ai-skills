                ad_dev_object_lock number generated by default on null as identity not null,
                object_owner varchar2(128 char) default user not null,
                object_type varchar2(30 char) not null,
                object_name varchar2(128 char) not null,
                lock_status varchar2(20 char) default 'ACTIVE' not null,
                locked_by varchar2(255 char) not null,
                branch_name varchar2(255 char),
                task_ref varchar2(500 char),
