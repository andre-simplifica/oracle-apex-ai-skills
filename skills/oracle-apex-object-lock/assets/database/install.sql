declare
    procedure add_column_if_missing (
        p_column_name in varchar2,
        p_definition  in varchar2
    )
    is
        l_count number;
    begin
        select count(*)
          into l_count
          from user_tab_columns
         where table_name = 'DEV_OBJECT_LOCK'
           and column_name = upper(p_column_name);

        if l_count = 0 then
            execute immediate
                'alter table dev_object_lock add (' ||
                dbms_assert.simple_sql_name(p_column_name) || ' ' ||
                p_definition || ')';
        end if;
    end add_column_if_missing;
begin
    add_column_if_missing('REPO_BASE_REF',  'VARCHAR2(255)');
    add_column_if_missing('REPO_HEAD_REF',  'VARCHAR2(255)');
    add_column_if_missing('REPO_START_SHA', 'VARCHAR2(64)');
    add_column_if_missing('REPO_END_SHA',   'VARCHAR2(64)');
end;
